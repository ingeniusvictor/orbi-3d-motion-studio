// LP-03A: a small, renderer-independent "cerebellum" for natural coupling.
// It does not generate independent movement. It coordinates EXISTING motor cues
// while preserving the source clip and the autonomy of the eyelook/hand layers.
import { springStep } from './motionPrimitives.js';

const rad = degrees => degrees*Math.PI/180;
const clamp = (x,a,b) => Math.max(a,Math.min(b,x));
export const MOTOR_MODES = Object.freeze({
  resting: Object.freeze({label:'Reposo',torso:0.55,arms:0.75,attention:0.55}),
  attentive: Object.freeze({label:'Escuchando',torso:0.50,arms:0.35,attention:1.00}),
  thinking: Object.freeze({label:'Pensando',torso:0.75,arms:0.55,attention:0.70}),
  explaining: Object.freeze({label:'Explicando',torso:0.75,arms:1.00,attention:0.90}),
});
const zero = () => ({x:0,v:0});
const ADD_ROLE = [
  'chest','upperChest','neck','leftShoulder','rightShoulder',
  'leftUpperArm','rightUpperArm','leftHand','rightHand',
];

export class MotorCoordinator {
  constructor(){
    this.enabled=false;
    this.intensity=0.42;
    this.mode='resting';
    this.appliedMode='resting';
    this.smoothed = {
      roll:zero(), yaw:zero(), attention:zero(),
      wristLeft:zero(), wristRight:zero(),
      torsoGain:zero(), armGain:zero(), attentionGain:zero(),
      active:zero(),
    };
    this.last={
      euler:{}, elbow:{left:0,right:0},mode:this.mode,
      enabled:false, maxDegrees:0,
    };
  }
  setEnabled(value){this.enabled=Boolean(value);}
  setIntensity(value){
    if(Number.isFinite(Number(value)))this.intensity=clamp(Number(value),0,1);
  }
  setMode(mode){
    if(!Object.hasOwn(MOTOR_MODES,mode))return false;
    this.mode=mode;
    return true;
  }
  getStatus(){
    return {
      enabled:this.enabled,intensity:this.intensity,
      mode:this.mode,modes:Object.keys(MOTOR_MODES),
      lastMaxDegrees:this.last.maxDegrees,
    };
  }
  reset(){
    for(const key of Object.keys(this.smoothed))this.smoothed[key]=zero();
    this.last={euler:{},elbow:{left:0,right:0},mode:this.mode,enabled:false,maxDegrees:0};
  }
  update(dt,{roll=0,yaw=0,headYaw=0,wristLeft=0,wristRight=0,activity=1}={}){
    const delta=clamp(Number(dt)||0,0,0.1);
    const finite=(value)=>Number.isFinite(value)?value:0;
    const gain=clamp(finite(activity),0,1);
    const amplitude=this.intensity*gain;
    const target=this.enabled?amplitude:0;
    const s=this.smoothed;
    s.active=springStep(s.active,target,delta,0.9);
    const mode=MOTOR_MODES[this.mode];
    s.torsoGain=springStep(s.torsoGain,mode.torso,delta,0.5);
    s.armGain=springStep(s.armGain,mode.arms,delta,0.5);
    s.attentionGain=springStep(s.attentionGain,mode.attention,delta,0.5);

    // Different response rates introduce causal delay; no additional noisy
    // oscillators or synchronized movements are generated by this module.
    s.roll=springStep(s.roll,clamp(finite(roll),-rad(2),rad(2)),delta,0.40);
    s.yaw=springStep(s.yaw,clamp(finite(yaw),-rad(2),rad(2)),delta,0.38);
    s.attention=springStep(s.attention,clamp(finite(headYaw),-rad(10),rad(10)),delta,0.48);
    s.wristLeft=springStep(s.wristLeft,clamp(finite(wristLeft),-1,1),delta,0.57);
    s.wristRight=springStep(s.wristRight,clamp(finite(wristRight),-1,1),delta,0.52);

    const strength=clamp(s.active.x,0,1);
    const torso=strength*clamp(s.torsoGain.x,0,1);
    const arms=strength*clamp(s.armGain.x,0,1);
    const attentive=strength*clamp(s.attentionGain.x,0,1);
    // The neck makes a small countercorrection as the upper torso follows
    // a gaze change, rather than moving all parts by the same angle.
    const followYaw=clamp(s.attention.x*0.20*attentive,-rad(0.7),rad(0.7));
    const torsoRoll=clamp(s.roll.x*0.26*torso,-rad(0.5),rad(0.5));
    const torsion=clamp(s.yaw.x*0.24*torso,-rad(0.4),rad(0.4));
    const leftHand=clamp(s.wristLeft.x*rad(0.65)*arms,-rad(0.65),rad(0.65));
    const rightHand=clamp(s.wristRight.x*rad(0.65)*arms,-rad(0.65),rad(0.65));
    const roles={
      chest: [0, followYaw*0.65+torsion*0.55, torsoRoll*0.45],
      upperChest: [0,followYaw*0.35+torsion*0.45,torsoRoll*0.35],
      neck: [0,-followYaw*0.18,-torsoRoll*0.12],
      leftShoulder: [0,-torsion*0.16,clamp(-torsoRoll*0.34+leftHand*0.15,-rad(0.4),rad(0.4))],
      rightShoulder: [0,-torsion*0.16,clamp(-torsoRoll*0.34-rightHand*0.15,-rad(0.4),rad(0.4))],
      leftUpperArm: [0,0,leftHand*0.35],
      rightUpperArm:[0,0,-rightHand*0.35],
      leftHand:[0,leftHand*0.18,0],
      rightHand:[0,rightHand*0.18,0],
    };
    const euler=Object.fromEntries(ADD_ROLE.map(role=>[role,roles[role]]));
    const elbow={left:clamp(Math.abs(s.wristLeft.x)*0.22*arms,0,0.22),
      right:clamp(Math.abs(s.wristRight.x)*0.22*arms,0,0.22)};
    let maxDegrees=0;
    for(const angles of Object.values(euler)){
      for(const angle of angles)maxDegrees=Math.max(maxDegrees,Math.abs(angle)*180/Math.PI);
    }
    this.last={euler,elbow,mode:this.mode,enabled:this.enabled,maxDegrees};
    return this.last;
  }
}
